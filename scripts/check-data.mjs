import assert from 'node:assert/strict';
import {createInitialState,derive,today,dateOffset,filterRecords,mutateRecord,setStatus,trainingVolume,recordValue,recordUnit} from '../src/data.js';
import {validateImport,exportData,loadState,saveState} from '../src/storage.js';
const state=createInitialState(),before=derive(state),current=state.records.find(r=>r.id==='train-today');
assert.equal(state.records.length,32);
assert.equal(validateImport(state).records.length,32);
assert.equal(before.today.completion,70);
assert.equal(before.trainingCount,6);
assert.equal(before.achievements.find(a=>a.kind==='milestone').value,5);
const recoveryPlan=state.records.find(r=>r.id==='plan-recovery');
assert.equal(recordValue(recoveryPlan),30,'无动作恢复计划显示时长');
assert.equal(recordUnit(recoveryPlan),'分钟');
const strengthPlan=state.records.find(r=>r.id==='plan-today');
assert.equal(recordValue(strengthPlan),1680,'有动作计划显示预计训练量');
assert.equal(recordUnit(strengthPlan),'kg');
assert.throws(()=>validateImport({...state,settings:{...state.settings,waterGoal:'不是数字'}}));
assert.throws(()=>validateImport({...state,settings:{...state.settings,weeklyTrainingGoal:NaN}}));
assert.throws(()=>validateImport({...state,records:state.records.map(r=>r.id==='body-3'?{...r,fields:{weight:'不是数字',fat:23.5}}:r)}));
assert.throws(()=>validateImport({...state,records:state.records.map(r=>r.id==='train-today'?{...r,fields:{duration:45,exercises:[{name:'哑铃卧推',sets:[{weight:NaN,reps:10,done:true}]}]}}:r)}));
const oneSet={...current,fields:{...current.fields,exercises:current.fields.exercises.map((e,i)=>({...e,sets:e.sets.map((s,j)=>({...s,done:i===0&&j===0}))}))}};
const changed=mutateRecord(state,oneSet);
assert.equal(trainingVolume(changed.records.find(r=>r.id===current.id)),200);
assert.equal(trainingVolume(current),0,'原始数据没有被改写');
assert.equal(derive(changed).trainingVolume,before.trainingVolume,'进行中训练暂不进入完成量');
const completed=setStatus(changed,current.id,'done'),after=derive(completed);
assert.equal(trainingVolume(completed.records.find(r=>r.id===current.id)),200,'完成只计实际勾选组');
assert.equal(completed.records.find(r=>r.id==='plan-today').status,'done');
assert.equal(after.trainingVolume,before.trainingVolume+200);
assert.equal(after.weeklyTrainingCount,before.weeklyTrainingCount+1);
assert.equal(after.trainingStreak,1);
assert(after.achievements.some(a=>a.recordId==='train-today'&&a.value===20));
assert.equal(after.today.completion,80);
assert.equal(completed.activities[0].recordId,current.id);
// 完成本次训练后，未来的下一次日期仍需提醒，逾期也保留。
const futureReminderState={...completed,records:completed.records.map(r=>r.id===current.id?{...r,nextDate:dateOffset(1)}:r)};
const futureReminder=derive(futureReminderState).nextReminders.find(r=>r.recordId===current.id);
assert.deepEqual({date:futureReminder.date,days:futureReminder.days,overdue:futureReminder.overdue},{date:dateOffset(1),days:1,overdue:false});
assert.equal(derive(completed).nextReminders.some(r=>r.recordId===current.id),false,'本次同日提醒在完成后消失');
const overdueReminderState={...completed,records:completed.records.map(r=>r.id===current.id?{...r,date:dateOffset(-3),nextDate:dateOffset(-1)}:r)};
const overdueReminder=derive(overdueReminderState).nextReminders.find(r=>r.recordId===current.id);
assert.deepEqual({days:overdueReminder.days,overdue:overdueReminder.overdue},{days:-1,overdue:true});

const added=mutateRecord(completed,{...state.records.find(r=>r.type==='body'),id:'new-body',date:today(),time:'21:00',fields:{weight:77.2,fat:23.4}});
assert.equal(added.records.length,33);
assert.equal(derive(added).weightTrend.at(-1).value,77.2);
const moved=mutateRecord(added,{...added.records.find(r=>r.id==='new-body'),date:dateOffset(1)});
assert(!filterRecords(moved.records,{from:today(),to:today()}).some(r=>r.id==='new-body'));
assert(filterRecords(moved.records,{from:dateOffset(1),to:dateOffset(1)}).some(r=>r.id==='new-body'));
const removed=mutateRecord(moved,current,'delete');
assert.equal(removed.records.length,32);
assert(!removed.activities.some(a=>a.recordId===current.id));
assert.equal(removed.records.find(r=>r.id==='plan-today').status,'planned');
const removedPlan=mutateRecord(state,state.records.find(r=>r.id==='plan-today'),'delete');
assert(!removedPlan.records.find(r=>r.id===current.id).planId);
assert(removedPlan.media.some(m=>m.id==='media-hero'),'原始素材目录保留，首页图片仍可查看');
const category=mutateRecord(state,{...current,id:'new-cat',category:'灵活性训练'});
assert(category.categories.includes('灵活性训练'));
assert.equal(derive(category).countsByCategory.find(c=>c.category==='灵活性训练').count,1);
assert.equal(filterRecords(state.records,{q:'深蹲',status:'done'}).length,4);
assert.throws(()=>validateImport({...state,records:[...state.records,{...current,id:'bad',mediaIds:['missing'],coverId:'missing'}]}));
assert.throws(()=>validateImport({...state,records:[...state.records,{...current,id:'bad',date:'2026-02-30'}]}));
assert.equal(validateImport(exportData(state)).records.length,32);
const planDone=setStatus(changed,'plan-today','done');
assert.equal(planDone.records.find(r=>r.id===current.id).status,'done');
assert.equal(trainingVolume(planDone.records.find(r=>r.id===current.id)),200);
// 生成报告的来源在删除后解除引用，保留报告当时的数值与明确说明。
const report=mutateRecord(state,{...state.records.find(r=>r.type==='record'),id:'saved-report',fields:{value:6,unit:'次',achievement:'阶段报告',sourceIds:['train-0829'],report:{sourceRecordIds:['train-0829'],trainingCount:6,achievements:[{recordId:'train-0829'}]}}});
const withoutSource=mutateRecord(report,state.records.find(r=>r.id==='train-0829'),'delete');
const savedReport=withoutSource.records.find(r=>r.id==='saved-report');
assert.deepEqual(savedReport.fields.sourceIds,[]);
assert.deepEqual(savedReport.fields.report.sourceRecordIds,[]);
assert.match(savedReport.notes,/1 条来源记录已移除/);
assert.equal(validateImport(withoutSource).records.length,32);
for(const mime of ['application/pdf','text/plain','text/csv','application/json','application/vnd.openxmlformats-officedocument.wordprocessingml.document','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet']){
  assert.equal(validateImport({...state,media:[...state.media,{id:`file-${mime}`,kind:'file',type:'training',src:`data:${mime};base64,YQ==`,title:'训练附件',date:today()}]}).media.length,8);
}
assert.throws(()=>validateImport({...state,media:[...state.media,{id:'bad-html',kind:'file',src:'data:text/html;base64,YQ=='}]}));
// 不依赖浏览器的降级路径：完整保存、刷新读取、坏文件保护、明确恢复。
const localValues=new Map();
globalThis.localStorage={getItem:k=>localValues.get(k)??null,setItem:(k,v)=>localValues.set(k,v),removeItem:k=>localValues.delete(k)};
const originalWarn=console.warn,originalError=console.error;
console.warn=()=>{};console.error=()=>{};
await loadState();await saveState(completed);
assert.equal((await loadState()).records.find(r=>r.id===current.id).status,'done');
localValues.set('jidong-state-v1','{损坏的备份');
await assert.rejects(loadState,/保留原文件/);
await assert.rejects(saveState(completed),/受保护/);
assert.equal(localValues.get('jidong-state-v1'),'{损坏的备份');
await saveState(completed,{replaceCorrupt:true});
assert.equal((await loadState()).records.length,32);
console.warn=originalWarn;console.error=originalError;
console.log(JSON.stringify({result:'PASS',records:32,completion:`${before.today.completion}% → ${after.today.completion}%`,completedVolume:`${before.trainingVolume} → ${after.trainingVolume} kg`,weeklyTraining:`${before.weeklyTrainingCount} → ${after.weeklyTrainingCount}`,checks:46,storage:'降级持久化、损坏保护、明确恢复均通过'}));
